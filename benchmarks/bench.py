"""Micro-benchmarks behind the numbers the README quotes.

Without arguments the table goes to stdout; with --write it replaces the one
in README.md between the markers, so the published numbers and the script
that produced them cannot drift apart.

Absolute nanoseconds move with the machine and a rerun lands within a few
percent; the ratios are the part worth reading.  Nothing here runs in CI:
timing on a shared runner measures the runner.
"""

from __future__ import annotations

import argparse
import platform
import sys
import timeit
from collections.abc import Sequence
from contextvars import ContextVar
from dataclasses import dataclass
from pathlib import Path

from nodrill import FromCtx, inject, injected, provider, use

README = Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- benchmarks: generated by benchmarks/bench.py, do not edit by hand -->"
END = "<!-- /benchmarks -->"


@dataclass
class Config:
    """The provided value; a dataclass because that is what callers use."""

    dsn: str = "postgres://"


@inject
def handler(_request: str, cfg: FromCtx[Config] = injected) -> str:
    """Read the dependency through @inject, with a leading positional argument."""
    return cfg.dsn


def in_body(_request: str) -> str:
    """Read the same dependency inside the body instead of injecting it."""
    return use(Config).dsn


# Label as it appears in the README, and the statement timeit runs for it.
CASES: tuple[tuple[str, str], ...] = (
    ("`use(Config)`", "use(Config)"),
    ("`use()` inside a function body, per call", "in_body('r')"),
    ("`@inject`, per call", "handler('r')"),
    ("`with provider(...)`, enter and exit", "\nwith provider(config):\n    pass\n"),
    ("reference: bare `ContextVar.get()`", "reference.get()"),
)


def measure(statement: str, namespace: dict[str, object]) -> float:
    """Return nanoseconds per loop for statement, letting timeit pick the count."""
    timer = timeit.Timer(statement, globals=namespace)
    loops, total = timer.autorange()
    # Best of five rather than one mean: a single run trails whatever else the
    # machine was doing during it.
    best = min(timer.repeat(repeat=5, number=loops))
    return min(total, best) / loops * 1e9


def run() -> list[tuple[str, float]]:
    """Time every case against a live provider."""
    config = Config()
    reference: ContextVar[Config] = ContextVar("reference")
    reference.set(config)
    with provider(config):
        namespace = {**globals(), **locals()}
        return [(label, measure(statement, namespace)) for label, statement in CASES]


def render(timings: Sequence[tuple[str, float]]) -> str:
    """Format timings as the markdown block the README carries."""
    width = max(len(label) for label, _ in timings)
    lines = [f"| {'operation':<{width}} | ns |", f"| {'-' * width} | --: |"]
    lines += [f"| {label:<{width}} | {round(ns):>3} |" for label, ns in timings]
    lines += [
        "",
        f"{platform.python_implementation()} {platform.python_version()}, {platform.machine()}.",
    ]
    return "\n".join(lines) + "\n"


def splice(document: str, table: str) -> str:
    """Return document with the region between the markers replaced by table."""
    start = document.index(START) + len(START)
    end = document.index(END, start)
    return f"{document[:start]}\n\n{table}\n{document[end:]}"


def main(argv: Sequence[str] | None = None) -> int:
    """Write the table to stdout, or into the README with --write."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--write",
        action="store_true",
        help="replace the table in README.md instead of writing to stdout",
    )
    args = parser.parse_args(argv)

    table = render(run())
    if not args.write:
        sys.stdout.write(table)
        return 0

    document = README.read_text(encoding="utf-8")
    if START not in document or END not in document:
        sys.stderr.write(f"{README}: markers {START} and {END} not found\n")
        return 1
    README.write_text(splice(document, table), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
