"""Micro-benchmarks behind the numbers the performance page quotes.

Without arguments the table goes to stdout, and with --write it replaces the
one in docs/content/misc/performance.rst between the markers, so the published
numbers and the script that produced them cannot drift apart.

The first rows are one function doing one read, reached six ways, so the rows
are comparable to each other and to handing the value in as a parameter, which
is what nodrill replaces.  Then the lookups on their own, what a scope costs
to open, and what carrying one to a worker costs.

Absolute nanoseconds move with the machine, so the whole table is timed
several times over and every row keeps its own best pass.  Timing one row to
completion before starting the next made each row hostage to whatever the
machine did during its own second, which moved the ratios as well, since the
baseline every ratio divides by is one of the rows.

A published number is only replaced when it moved further than a rerun moves
it, so running this on an unchanged tree writes nothing and a diff means a
real change.  Two revisions are told apart with --save on one and --against
on the other, which prints the deltas and says which of them a rerun would
not explain.  Nothing here runs in CI, because timing on a shared runner
measures the runner.
"""

from __future__ import annotations

import argparse
import json
import platform
import re
import sys
import timeit
from collections.abc import Mapping, Sequence
from contextlib import ExitStack
from contextvars import ContextVar
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from nodrill import Executor, FromCtx, debug, inject, injected, lazy, provider, ref, use, wrap

PAGE = Path(__file__).resolve().parent.parent / "docs/content/misc/performance.rst"
START = ".. benchmarks generated by benchmarks/bench.py, do not edit by hand"
END = ".. end benchmarks"

# Deep enough that a per-provider cost would show, shallow enough to stay realistic.
STACK_DEPTH = 8

# Deep enough that the slope shows rather than hiding under the fixed cost of a block.
DEEP_STACK = 64

# What a request scope carries by the time the layers are done accumulating.
NAMESPACE_WIDTH = 8

# Enough passes that a row unlucky in one of them is measured fairly in another.
PASSES = 5

# What a rerun moves a row by, below which the published number is left alone.
NOISE = 0.08


@dataclass
class Config:
    """The provided value, a dataclass because that is what callers use."""

    dsn: str = "postgres://"


@inject
def read_injected(_request: str, cfg: FromCtx[Config] = injected) -> str:
    """Read the dependency through @inject, with a leading positional argument."""
    return cfg.dsn


def read_used(_request: str) -> str:
    """Read the same dependency inside the body instead of injecting it."""
    return use(Config).dsn


def read_passed(_request: str, cfg: Config) -> str:
    """Take the same dependency as a parameter, which is what nodrill replaces."""
    return cfg.dsn


# Points at the Config above, so the row prices the borrowed hash and nothing else.
CONFIG_REF = ref(f"{__name__}:Config")


def noop() -> None:
    """Do nothing, so the wrap() and Executor rows price the carry and not its target."""


# Labels are the performance page's row headings, so changing one rewrites the published table.
PASSED = "one read in a function, value passed in as a parameter"
USED = "the same read through `use()`"
INJECTED = "the same read through `@inject`"
FROZEN = "the same read through a `frozen=True` provider"
SEALED = "the same read through a `sealed=True` provider"
LAZY = "the same read through a resolved `lazy` provider"
ALONE = "`use(Config)` on its own, without the call frame"
ATTRIBUTE = "`use('scope').field`, one attribute off a namespace"
REF = "the same lookup through a `ref()` key"
FALLBACK = "`use('absent', default=...)`, a miss that falls back"
COUNTED = "`use(Config)` under `debug(unused=True)`"
REFERENCE = "bare `ContextVar.get()`, for reference"
ENTER = "`with provider(...)`, enter and exit"
STACKED = f"the same with {STACK_DEPTH} providers already open"
DEEP = f"the same with {DEEP_STACK} providers already open"
SEALED_ENTER = "`with provider(..., sealed=True)`, entered and exited"
LAZY_ENTER = "`with provider(lazy(...))`, entered and exited unread"
EXTEND = f"`with provider(..., extend=True)`, over an {NAMESPACE_WIDTH}-attribute namespace"
REPLAY = "`wrap(fn)()`, the context replay per call"
WORKER = "`Executor.submit(fn).result()`, a round trip through a worker"

# Handing the value in is the alternative nodrill replaces, so it is what the ratios divide by.
BASELINE = PASSED

# The published order, comparable reads first, then the lookups, the scopes and the handoffs.
ORDER = (
    PASSED,
    USED,
    INJECTED,
    FROZEN,
    SEALED,
    LAZY,
    ALONE,
    ATTRIBUTE,
    REF,
    FALLBACK,
    COUNTED,
    REFERENCE,
    ENTER,
    STACKED,
    DEEP,
    SEALED_ENTER,
    LAZY_ENTER,
    EXTEND,
    REPLAY,
    WORKER,
)

ENTER_STATEMENT = "\nwith provider(config):\n    pass\n"
SEALED_ENTER_STATEMENT = "\nwith provider(config, sealed=True):\n    pass\n"
LAZY_ENTER_STATEMENT = "\nwith provider(lazy(Config, Config)):\n    pass\n"
EXTEND_STATEMENT = "\nwith provider('scope', extend=True, added=1):\n    pass\n"

# The cases that share one live provider for Config, which is one entry in the registry.
PROVIDED: tuple[tuple[str, str], ...] = (
    (PASSED, "read_passed('r', config)"),
    (USED, "read_used('r')"),
    (INJECTED, "read_injected('r')"),
    (ALONE, "use(Config)"),
    (REF, "use(CONFIG_REF)"),
    (FALLBACK, "use('absent', default=None)"),
    (REFERENCE, "reference.get()"),
    (ENTER, ENTER_STATEMENT),
    (SEALED_ENTER, SEALED_ENTER_STATEMENT),
    (LAZY_ENTER, LAZY_ENTER_STATEMENT),
    (REPLAY, "bound()"),
)


def measure(
    label: str, statement: str, namespace: dict[str, object], loops: dict[str, int]
) -> float:
    """Return nanoseconds per loop, reusing the loop count this row settled on in pass one."""
    timer = timeit.Timer(statement, globals=namespace)
    count = loops.get(label)
    if count is None:
        count, total = timer.autorange()
        loops[label] = count
        return total / count * 1e9
    return timer.timeit(count) / count * 1e9


def best_of(passes: int) -> dict[str, float]:
    """Time the whole table repeatedly and keep each row's best pass.

    Noise only ever adds time, so the minimum is the estimate, and taking it
    across passes rather than within one row is what stops a row that was
    timed during a bad second from being the published number.
    """
    loops: dict[str, int] = {}
    best: dict[str, float] = {}
    for number in range(passes):
        timings = run(loops)
        if not number:
            checked(timings)
        for label, timing in timings.items():
            best[label] = min(best.get(label, timing), timing)
    return best


def checked(timings: Mapping[str, float]) -> None:
    """Refuse a run and an ORDER that disagree, after one pass rather than at render."""
    missing = [label for label in ORDER if label not in timings]
    unpublished = [label for label in timings if label not in ORDER]
    if missing or unpublished:
        raise KeyError(f"ORDER and run() disagree, missing {missing}, unpublished {unpublished}")


def run(loops: dict[str, int]) -> dict[str, float]:
    """Time every case once, each under the context its row describes."""
    config = Config()
    reference: ContextVar[Config] = ContextVar("reference")
    reference.set(config)

    with provider(config):
        bound = wrap(noop)
        namespace = {**globals(), **locals()}
        timings = {label: measure(label, stmt, namespace, loops) for label, stmt in PROVIDED}

    # The frozen row reuses read_used, so its delta is the proxy and nothing else.
    with provider(config, frozen=True):
        timings[FROZEN] = measure(FROZEN, "read_used('r')", {**globals(), **locals()}, loops)

    # The sealed row is the same read again, so its delta is the liveness check and nothing else.
    with provider(config, sealed=True):
        timings[SEALED] = measure(SEALED, "read_used('r')", {**globals(), **locals()}, loops)

    # And the lazy row prices the cell after the first read has already resolved it.
    with provider(lazy(Config, Config)):
        timings[LAZY] = measure(LAZY, "read_used('r')", {**globals(), **locals()}, loops)

    # Counting is what a recorded contract installs too, so this row prices both.
    with debug(unused=True), provider(config):
        timings[COUNTED] = measure(COUNTED, "use(Config)", {**globals(), **locals()}, loops)

    # An extending layer copies the enclosing namespace too, so it is priced over a full one.
    with provider("scope", **{f"field{i}": i for i in range(NAMESPACE_WIDTH)}):
        namespace = {**globals(), **locals()}
        timings[EXTEND] = measure(EXTEND, EXTEND_STATEMENT, namespace, loops)
        # The shape extend=True and adopt() both produce, which is a lookup and one getattr.
        timings[ATTRIBUTE] = measure(ATTRIBUTE, "use('scope').field0", namespace, loops)

    # Entering copies the registry, so the claim that the copy scales with depth is priced here.
    for label, depth in ((STACKED, STACK_DEPTH), (DEEP, DEEP_STACK)):
        with ExitStack() as stack:
            for layer in range(depth):
                stack.enter_context(provider(f"layer{layer}"))
            timings[label] = measure(label, ENTER_STATEMENT, {**globals(), **locals()}, loops)

    # A real handoff, so the replay row above is not read as the price of a thread.
    with provider(config), Executor(max_workers=1) as pool:
        pool.submit(noop).result()
        timings[WORKER] = measure(
            WORKER, "pool.submit(noop).result()", {**globals(), **locals()}, loops
        )

    return timings


def line(cells: Sequence[str], widths: Sequence[int]) -> str:
    """Format one row, padded to the column widths the whole table shares."""
    return "  ".join(cell.ljust(width) for cell, width in zip(cells, widths, strict=True)).rstrip()


def table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    """Format rows as the reStructuredText simple table both outputs share."""
    widths = [max(len(cell) for cell in column) for column in zip(header, *rows, strict=True)]
    rule = "  ".join("=" * width for width in widths)
    return "\n".join([rule, line(header, widths), rule, *(line(row, widths) for row in rows), rule])


def render(timings: Mapping[str, float]) -> str:
    """Format timings as the reStructuredText block the performance page carries."""
    base = timings[BASELINE]
    # The multiplication sign, since that is the heading the published table carries.
    header = ("operation", "ns", "×")  # noqa: RUF001
    # Divided after rounding, so the table is a function of its own ns column and a rerun settles.
    rows = [
        (label, f"{round(timings[label])}", ratio(round(timings[label]) / round(base)))
        for label in ORDER
    ]
    return table(header, rows)


def compared(fresh: Mapping[str, float], old: Mapping[str, float]) -> str:
    """Format this run against a saved one, so a real change reads apart from the weather."""
    rows = []
    for label in ORDER:
        now = fresh[label]
        was = old.get(label)
        if was is None:
            rows.append((label, "-", f"{round(now)}", "-", "new"))
            continue
        change = (now - was) / was
        verdict = "moved" if abs(change) > NOISE else "settled"
        rows.append((label, f"{round(was)}", f"{round(now)}", f"{change:+.0%}", verdict))
    return table(("operation", "was", "now", "change", "verdict"), rows)


def machine() -> str:
    """Describe the interpreter and the machine, which a comparison has to hold fixed."""
    where = platform.platform(terse=True).replace("-", " ")
    return (
        f"{platform.python_implementation()} {platform.python_version()} "
        f"on {where}, {platform.machine()}"
    )


def stamp() -> str:
    """Describe the interpreter, the machine and the day that produced these numbers."""
    return f"{machine()}, measured {date.today().isoformat()}."  # noqa: DTZ011


def ratio(times: float) -> str:
    """Format a multiple of the baseline, keeping a decimal only where it says something."""
    return f"{times:.1f}" if times < 10 else str(round(times))  # noqa: PLR2004


# One row of the rendered table, which is how the page hands its numbers back.
ROW = re.compile(r"^(\S.*?)\s{2,}(\d+)\s{2,}[\d.]+$")


def carried(document: str) -> str:
    """Return the table the page carries right now, rules included, so it can be compared."""
    start = document.index(START)
    end = document.index(END, start)
    block = document[start:end].splitlines()
    rules = [number for number, line in enumerate(block) if line.startswith("==")]
    if not rules:
        return ""
    return "\n".join(block[rules[0] : rules[-1] + 1])


def published(table_text: str) -> dict[str, float]:
    """Read the numbers the page already carries, so a rerun can leave them where they are."""
    found = (ROW.match(line) for line in table_text.splitlines())
    return {row[1]: float(row[2]) for row in found if row is not None and row[1] != "operation"}


def steadied(fresh: Mapping[str, float], old: Mapping[str, float]) -> dict[str, float]:
    """Keep every published number a rerun would only have jittered.

    A row moves when it moved further than a rerun moves it, so the diff of
    this page is a signal rather than the weather on the machine that ran it.
    """
    kept = {}
    for label, timing in fresh.items():
        was = old.get(label)
        settled = was is not None and abs(timing - was) <= was * NOISE
        kept[label] = was if settled else timing
    return kept


def splice(document: str, table_text: str) -> str:
    """Return document with the region between the markers replaced by the table."""
    start = document.index(START) + len(START)
    end = document.index(END, start)
    return f"{document[:start]}\n\n{table_text}\n{document[end:]}"


def write_page(timings: Mapping[str, float]) -> int:
    """Rewrite the rows of the performance page that moved, and report what changed."""
    document = PAGE.read_text(encoding="utf-8")
    if START not in document or END not in document:
        sys.stderr.write(f"{PAGE}: markers {START} and {END} not found\n")
        return 1
    was = carried(document)
    old = published(was)
    steady = steadied(timings, old)
    fresh = render(steady)
    if set(published(fresh)) != set(ORDER):
        sys.stderr.write(f"{PAGE}: the table does not read back as its own rows, nothing written\n")
        return 1
    if fresh == was:
        sys.stderr.write(f"{PAGE}: every row is within {NOISE:.0%} of what it says, left alone\n")
        return 0
    PAGE.write_text(splice(document, f"{fresh}\n\n{stamp()}\n"), encoding="utf-8")
    moved = [label for label in ORDER if round(steady[label]) != old.get(label)]
    sys.stderr.write(f"{PAGE}: rewrote {len(moved)} of {len(ORDER)} rows\n")
    for label in moved:
        sys.stderr.write(f"  {old.get(label)} -> {round(steady[label])}  {label}\n")
    return 0


def against(timings: Mapping[str, float], source: str) -> int:
    """Print this run against the one saved in source, refusing another machine's numbers."""
    saved = json.loads(Path(source).read_text(encoding="utf-8"))
    if saved.get("machine") != machine():
        sys.stderr.write(
            f"{source} was saved on {saved.get('machine')} and this is {machine()}, "
            f"so the deltas would mean nothing\n"
        )
        return 1
    sys.stdout.write(f"{compared(timings, saved['timings'])}\n\n{stamp()}\n")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Write the table to stdout, into the performance page, or against a saved run."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--passes",
        type=int,
        default=PASSES,
        metavar="N",
        help="how many times to time the whole table, keeping each row's best pass",
    )
    parser.add_argument(
        "--save",
        metavar="FILE",
        help="also write the raw timings as JSON, for another revision to compare against",
    )
    output = parser.add_mutually_exclusive_group()
    output.add_argument(
        "--write",
        action="store_true",
        help="update the rows of the performance page that moved, instead of writing to stdout",
    )
    output.add_argument(
        "--against",
        metavar="FILE",
        help="print the deltas against timings --save wrote, instead of a table of ns",
    )
    args = parser.parse_args(argv)
    if args.passes < 1:
        parser.error("--passes takes a positive count")

    timings = best_of(args.passes)
    if args.save:
        saved = {"machine": machine(), "timings": timings}
        Path(args.save).write_text(json.dumps(saved, indent=2), encoding="utf-8")
        sys.stderr.write(f"{args.save}: saved {len(timings)} rows\n")

    if args.against:
        return against(timings, args.against)
    if args.write:
        return write_page(timings)
    sys.stdout.write(f"{render(timings)}\n\n{stamp()}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
